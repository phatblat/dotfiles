# Content patterns that disqualify an otherwise config-shaped file.
SECRET_CONTENT = (
    ("openai-style key", re.compile(r"\bsk-[A-Za-z0-9_-]{16,}")),
    ("github token", re.compile(r"\b(gh[pousr]_[A-Za-z0-9]{16,}|github_pat_[\w]{20,})")),
    ("aws access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("slack token", re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}")),
    ("private key block", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("jwt", re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.")),
    (
        "assigned credential",
        re.compile(
            # allow an optional closing quote after the key so JSON
            # ("apiKey": "…") matches as well as shell/yaml (key=value) forms.
            # Env-var-shaped names (apiKey: SOME_API_KEY) are not secrets, so
            # skip ALL_CAPS values that contain at least one underscore; an
            # all-caps literal with no underscore (hex/base32) is still caught.
            r"(?i)\b(api[_-]?key|secret|password|passwd|access[_-]?token|bearer)"
            r"\b[\"']?\s*[:=]\s*[\"']?"
            r"(?-i:(?![A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+(?:[\"'\s,;}]|\Z)))"
            r"[A-Za-z0-9_\-./+]{16,}"
        ),
    ),
    # Not a credential, but the same never-track class: a trust grant records a
    # directory vetted on one machine. Copying it auto-approves that path on a
    # fresh host. Caught by name as trust.json; this catches it as a key, and as
    # a Codex `[projects."<path>"]` `trust_level = "trusted"` line.
    (
        "trust grant",
        re.compile(
            r"(?im)\"(trusted[_-]?(workspaces|folders|paths|dirs|roots)"
            r"|workspace[_-]?trust)\"\s*:\s*\[\s*[^\]\s]"
            r"|^\s*trust_level\s*=\s*\"trusted\""
        ),
    ),
)

# Tracked files whose credential-shaped names or content are not credentials —
# verified false positives. user-prompt-secrets.sh is the secret-warning hook
# itself; loopback-expert.md is an agent prompt whose example code reads
# `process.env.DB_PASSWORD`.
TRACKED_ALLOWLIST = frozenset(
    {
        ".claude/agents-disabled/loopback/loopback-expert.md",
        ".claude/hooks/scripts/user-prompt-secrets.sh",
        ".codex/hooks/scripts/user-prompt-secrets.sh",
    }
)

CONTENT_SCAN_LIMIT = 1 << 20  # 1 MiB

# Documentation a CLI writes into its own config root on install or upgrade.
# Shipped artifacts, never hand-authored configuration.
BUNDLED_DOC_NAMES = frozenset(
    {
        "readme.md",
        "readme",
        "changelog.md",
        "license",
        "license.md",
        "license.txt",
        "notice",
    }
)

# Single files an installer writes into a harness root. Each reinstalls on
# any machine, so it is state, never a candidate. Data Agent Kit writes
# .gemini/config/mcp_config.json (harness-map closed item, 2026-10-25).
INSTALLED_PATHS = frozenset(
    {
        ".gemini/config/mcp_config.json",
        ".claude/plugins/blocklist.json",
        ".claude/plugins/installed_plugins.json",
        ".claude/policy-limits.json",
        ".claude/remote-settings.json",
    }
)


def classify(relpath):
    """Return 'secret', 'state', 'config', or 'other' for a repo-relative path."""
    path = Path(relpath)
    name = path.name
    lower = name.lower()

    if name in SECRET_NAMES or lower.startswith(".env."):
        return "secret"
    if lower.endswith(SECRET_SUFFIXES) or SECRET_WORDS.search(lower):
        return "secret"

    if STATE_DIRS.intersection(path.parts[:-1]):
        return "state"
    if name in STATE_NAMES or lower.endswith(STATE_SUFFIXES):
        return "state"
    if any(STATE_SHAPES.search(part) for part in path.parts):
        return "state"

    if path.suffix.lower() in CONFIG_SUFFIXES:
        return "config"
    return "other"


def sniff_bytes(blob):
    """Return names of secret patterns found in blob, or [] if clean."""
    if b"\0" in blob[:8192]:
        return []
    text = blob.decode("utf-8", errors="replace")
    return [label for label, pattern in SECRET_CONTENT if pattern.search(text)]


def sniff_secrets(path):
    """Return names of secret patterns found in a file, or [] if clean."""
    try:
        blob = path.read_bytes()[:CONTENT_SCAN_LIMIT]
    except OSError:
        return []
    return sniff_bytes(blob)


def staged_bytes(repo, relpath):
    """Return a tracked path's index bytes (post-clean-filter), or None."""
    result = subprocess.run(
        ["git", "-C", str(repo), "cat-file", "blob", f":{relpath}"],
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        return None
    return result.stdout[:CONTENT_SCAN_LIMIT]


def is_package_root(repo, reldir, memo):
    """True if reldir holds a vendor marker, memoized per directory."""
    cached = memo.get(reldir)
    if cached is None:
        cached = any((repo / reldir / marker).exists() for marker in VENDOR_MARKERS)
        memo[reldir] = cached
    return cached


def is_vendored(repo, relpath, memo, stop_at=frozenset()):
    """True if relpath sits inside a third-party package or nested clone.

    A vendor marker sitting at a scan root itself (e.g. the package.json a
    harness npm-installs plugins into its own config dir with) does not vendor
    hand-authored files living directly at that root — only nested packages do.
    """
    parent = Path(relpath).parent
    while parent != Path(".") and str(parent) not in stop_at:
        if is_package_root(repo, parent, memo):
            return True
        parent = parent.parent
    return False


def is_unshared_skill(repo, relpath):
    """True if relpath is a native skill with no `.agents/skills` counterpart."""
    for root in NATIVE_SKILL_ROOTS:
        prefix = f"{root}/"
        if relpath.startswith(prefix):
            name = relpath[len(prefix) :].split("/", 1)[0]
            return not (repo / ".agents" / "skills" / name).is_dir()
    return False


def is_bundled_doc(relpath):
    """True if relpath is documentation a CLI ships into its own config root
    (`<root>/README.md`). No one hand-authors a README as harness
    configuration, so match the shape rather than one path.
    """
    parts = Path(relpath).parts
    return len(parts) == 2 and parts[1].lower() in BUNDLED_DOC_NAMES


def is_empty(path):
    """True if path is a zero-byte file.

    An empty file carries no configuration to replicate. `classify()` reaches
    `config` on the `.json` suffix alone, which kept surfacing a 0-byte
    pre-migration orphan (`~/.gemini/config/mcp_config.json`) as a candidate.
    """
    try:
        return path.stat().st_size == 0
    except OSError:
        return False


def git_lines(repo, args):
    """Run a git command in repo and return its NUL-separated output as a list."""
    result = subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True,
        text=True,
        check=True,
    )
    return [line for line in result.stdout.split("\0") if line]


def classify_entry(repo, base, entry, vendored, roots, source):
    """Classify one untracked file; None unless it is config or state.

    `base` is the tree the file lives in (the checkout or $HOME); `repo` is
    always the checkout, which owns the shared-skill counterparts.
    """
    kind = "state" if entry in INSTALLED_PATHS else classify(entry)
    if kind == "state":
        return {"path": entry, "kind": "state", "warnings": [], "source": source}
    if kind not in ("config",):
        return None
    if (
        is_vendored(base, entry, vendored, roots)
        or is_unshared_skill(repo, entry)
        or is_bundled_doc(entry)
        or is_empty(base / entry)
    ):
        kind = "state"
    record = {"path": entry, "kind": kind, "warnings": [], "source": source}
    if kind == "config":
        record["warnings"] = sniff_secrets(base / entry)
        if record["warnings"]:
            record["kind"] = "review"
    return record


def scan_ignored(repo, roots):
    """Classify every ignored, untracked file under roots."""
    found = []
    vendored = {}
    for entry in git_lines(
        repo, ["ls-files", "-z", "--others", "--ignored", "--exclude-standard", "--", *roots]
    ):
        record = classify_entry(repo, repo, entry, vendored, roots, "checkout")
        if record:
            found.append(record)
    return found


def scan_home(repo, home, roots, tracked):
    """Classify regular files under roots in $HOME that the checkout does not deploy.

    The home overlay links only tracked files into $HOME, so a file a harness
    writes there directly is invisible to `git ls-files` in the checkout.
    """
    found = []
    vendored = {}
    for root in roots:
        top = home / root
        if not top.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(top):
            dirnames[:] = sorted(d for d in dirnames if d not in STATE_DIRS)
            for name in sorted(filenames):
                path = Path(dirpath) / name
                if path.is_symlink() or not path.is_file():
                    continue
                entry = path.relative_to(home).as_posix()
                if entry in tracked or os.path.lexists(repo / entry):
                    continue
                record = classify_entry(repo, home, entry, vendored, roots, "home")
                if record:
                    found.append(record)
    return found


def scan_tracked(repo, roots):
    """Flag tracked files that are named or shaped like credentials.

    Content warnings are confirmed against the index rather than the worktree.
    A path with a `filter=` clean filter in .gitattributes is scrubbed on its
    way into git, so the worktree copy can hold a trust grant or a token that
    never reaches a blob. Judging the worktree reports a leak that does not
    exist — and reports it again on every audit. The index lookup costs one
    subprocess and only runs for a file the cheap worktree scan already
    flagged.
    """
    flagged = []
    for entry in git_lines(repo, ["ls-files", "-z", "--", *roots]):
        if entry in TRACKED_ALLOWLIST:
            continue
        warnings = sniff_secrets(repo / entry)
        if warnings:
            staged = staged_bytes(repo, entry)
            if staged is not None:
                warnings = sniff_bytes(staged)
        if classify(entry) == "secret":
            warnings = ["credential-shaped name", *warnings]
        if warnings:
            flagged.append({"path": entry, "warnings": warnings})
    return flagged


def display_path(item):
    """Checkout paths print as-is; $HOME paths carry a `~/` prefix."""
    return f"~/{item['path']}" if item.get("source") == "home" else item["path"]


def render(candidates, review, state, flagged, include_state):
    """Print a markdown report. Returns nothing."""
    print("## Ignored configuration coverage\n")

    if candidates:
        print("### Candidates worth tracking\n")
        print("| Path | Size |")
        print("|---|---|")
        for item in candidates:
            print(f"| `{display_path(item)}` | {item['size']} B |")
        print()
    else:
        print("No untracked configuration candidates. Coverage is complete.\n")

    if review:
        print("### Config-shaped but contains credential material — do not track as-is\n")
        print("| Path | Detected |")
        print("|---|---|")
        for item in review:
            print(f"| `{display_path(item)}` | {', '.join(item['warnings'])} |")
        print()

    if flagged:
        print("### Tracked files that look like credentials — audit these\n")
        print("| Path | Detected |")
        print("|---|---|")
        for item in flagged:
            print(f"| `{item['path']}` | {', '.join(item['warnings'])} |")
        print()

    if include_state and state:
        print(f"### Ignored runtime state ({len(state)} files, correctly excluded)\n")
        for item in state[:50]:
            print(f"- `{display_path(item)}`")
        if len(state) > 50:
            print(f"- ... and {len(state) - 50} more")
        print()


def allowlist_roots(repo):
    """Derive curated allowlist-governed roots from the repo .gitignore."""
    ignore_file = repo / ".gitignore"
    if not ignore_file.is_file():
        return []
    denied = set()
    curated = set()
    for line in ignore_file.read_text().splitlines():
        line = line.strip()
        deny = DENY_RULE.fullmatch(line)
        if deny:
            denied.add(deny.group(1))
            continue
        keep = REINCLUDE_RULE.fullmatch(line)
        if keep:
            curated.add(keep.group(1))
    # Curation can be declared at any depth: `!.omp/agent/config.yml` curates
    # `.omp`. Match a denied root against every re-included ancestor path.
    roots = {
        root
        for root in denied
        if (repo / root).is_dir()
        and any(kept == root or kept.startswith(root + "/") for kept in curated)
    }
    # Keep only outermost roots; nested `<root>/sub/*` rules add no coverage.
    outermost = {r for r in roots if not any(r.startswith(o + "/") for o in roots - {r})}
    return sorted(outermost & HARNESS_ROOTS)


def main():
    parser = argparse.ArgumentParser(description=(__doc__ or "").partition("\n")[0])
    parser.add_argument("roots", nargs="*", help="paths to scan (default: allowlisted roots)")
    parser.add_argument("--repo", default=str(Path(__file__).resolve().parent.parent), help="repository root")
    parser.add_argument("--json", action="store_true", help="emit JSON instead of markdown")
    parser.add_argument(
        "--include-state", action="store_true", help="also list ignored runtime state"
    )
    parser.add_argument(
        "--home",
        default=str(Path.home()),
        help="home directory whose harness roots are scanned for untracked files",
    )
    args = parser.parse_args()

    repo = Path(args.repo).expanduser().resolve()
    home = Path(args.home).expanduser().resolve()
    roots = args.roots or allowlist_roots(repo)
    if not roots:
        print("No config roots found to scan.", file=sys.stderr)
        return 0

    tracked = set(git_lines(repo, ["ls-files", "-z", "--", *roots]))
    ignored = scan_ignored(repo, roots) + scan_home(repo, home, roots, tracked)
    candidates = []
    for item in (i for i in ignored if i["kind"] == "config"):
        base = home if item["source"] == "home" else repo
        item["size"] = (base / item["path"]).stat().st_size
        candidates.append(item)
    candidates.sort(key=lambda i: i["path"])
    review = sorted((i for i in ignored if i["kind"] == "review"), key=lambda i: i["path"])
    state = sorted((i for i in ignored if i["kind"] == "state"), key=lambda i: i["path"])
    # The ignored-file scan only makes sense for allowlist-governed roots, but a
    # tracked credential can sit under any harness root, including the ones
    # (.claude, .agents) that are not allowlist-governed. Explicit roots narrow both.
    tracked_roots = roots if args.roots else sorted(HARNESS_ROOTS)
    flagged = scan_tracked(repo, tracked_roots)

    if args.json:
        json.dump(
            {
                "roots": roots,
                "candidates": candidates,
                "review": review,
                "state": state if args.include_state else [],
                "tracked_flagged": flagged,
            },
            sys.stdout,
            indent=2,
        )
        print()
    else:
        render(candidates, review, state, flagged, args.include_state)
    return 0


if __name__ == "__main__":
    sys.exit(main())
