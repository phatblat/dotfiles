def find_orphans(expected: dict[Path, str]) -> list[Path]:
    orphans: list[Path] = []
    for root, pattern in GENERATED_ITEM_ROOTS:
        if not root.is_dir():
            continue
        for path in sorted(root.rglob(pattern)):
            if path not in expected:
                orphans.append(path)
    return orphans


def command_generate(*, check: bool) -> int:
    expected = render_all()
    stale: list[Path] = []
    obsolete = find_obsolete_skill_wrappers(expected)

    for path, content in expected.items():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(path)

    orphans = find_orphans(expected)

    if check:
        for path in stale:
            print(f"stale: {display_path(path)}", file=sys.stderr)
        for path in orphans:
            print(f"orphan: {display_path(path)}", file=sys.stderr)
        for path in obsolete:
            print(f"obsolete: {display_path(path)}", file=sys.stderr)
        return 1 if stale or orphans or obsolete else 0

    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    roots = {root for root, _ in GENERATED_ITEM_ROOTS}
    for path in orphans:
        path.unlink()
        parent = path.parent
        while parent not in roots and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent

    for path in obsolete:
        path.unlink()
        try:
            path.parent.rmdir()
        except OSError:
            pass
    return 0


def find_obsolete_skill_wrappers(expected: dict[Path, str]) -> list[Path]:
    expected_paths = set(expected)
    obsolete: list[Path] = []
    adapters = [
        (ANTIGRAVITY_HARNESS / "skills", render_antigravity_skill),
        (CURSOR_HARNESS / "skills", render_cursor_skill),
    ]

    for root, render in adapters:
        if not root.is_dir() or root.is_symlink():
            continue
        for path in root.glob("*/SKILL.md"):
            if (
                path in expected_paths
                or path.is_symlink()
                or path.parent.is_symlink()
                or not path.is_file()
            ):
                continue
            if is_generated_pointer(path.read_text(), path.parent.name):
                obsolete.append(path)

    return sorted(obsolete)


def command_validate() -> int:
    errors: list[str] = []
    inventory = build_inventory()
    if len(inventory["commands"]) != 26:
        errors.append(
            f"expected 26 active commands, found {len(inventory['commands'])}"
        )
    if len(inventory["agents"]) != 6:
        errors.append(f"expected 6 specialist agents, found {len(inventory['agents'])}")
    if inventory["skills"]["count"] < 1:
        errors.append("expected shared skills in .agents/skills")
    if command_generate(check=True) != 0:
        errors.append("generated artifacts are stale")

    for config in (
        OPEN_CODE / "opencode.jsonc",
        PI_AGENT / "settings.json",
        ROOT / "docs" / "agent-harnesses.json",
        ANTIGRAVITY_HARNESS / "plugin.json",
        ANTIGRAVITY_HARNESS / "hooks" / "hooks.json",
        ANTIGRAVITY_HARNESS / "mcp.json",
        CURSOR_HARNESS / "hooks" / "hooks.json",
        CURSOR_HARNESS / "mcp.json",
        GROK / "hooks" / "harness-guard.json",
    ):
        try:
            json.loads(config.read_text())
        except Exception as exc:  # noqa: BLE001 - report all parse failures
            errors.append(
                f"{display_path(config)} is not valid JSON/JSONC subset: {exc}"
            )

    if shutil.which("opencode"):
        result = subprocess.run(
            ["opencode", "debug", "config", "--pure"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            errors.append("opencode debug config --pure failed")

    if shutil.which("pi"):
        result = subprocess.run(
            ["pi", "list", "--no-approve"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            errors.append("pi list --no-approve failed")

    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print("Agent harness parity checks passed")
    return 0


