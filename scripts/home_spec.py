#!/usr/bin/env python3
"""home_spec: generates the `mise dot` deploy spec for the dotfiles repo.

mise's `symlink-each` mode into `~` must walk the whole home directory (including
mounts such as ~/OrbStack) to find stale links, which does not finish on this
machine. So every deployed file gets its own explicit `symlink` entry, which
mise applies without scanning anything. The spec is generated from `git ls-files`
and committed at .config/mise/conf.d/dotfiles.toml (deployed to
~/.config/mise/conf.d/dotfiles.toml like any other tracked file).

Classes of tracked path:
  linked        every path not listed below: ~/<p> -> ~/dev/dotfiles/<p>
  repo-only     tooling that never appears in $HOME (REPO_ONLY)
  launchd       plists that install-launchagents/-daemons copy (launchd ignores links)
  copy-class    app-owned files whose committed blob is scrubbed by a clean filter;
                seeded once as copies, captured back with `just home-capture`
  out-of-repo   tracked symlinks whose relative target leaves the repo; deployed as
                direct links to their real sources
  dangling      tracked symlinks to absolute paths that may not exist (mise only
                links to existing sources); `links` recreates them with the repo's
                own link text

Usage:
  home_spec.py generate [--repo DIR]   rewrite the spec
  home_spec.py check [--repo DIR]      exit 1 when the spec is stale
  home_spec.py links [--repo DIR]      recreate the dangling-class links in $HOME

Copyright: Ben Chatelain. MIT.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

# Where the primary checkout lives on every machine that deploys this spec. The
# committed spec must be byte-identical everywhere, so this is a convention, not
# something derived per machine (home-capture, home-apply-hook, and home.just
# derive the live checkout from `git rev-parse --git-common-dir` instead). A
# clone elsewhere needs `generate --source <dir>` and an uncommitted spec.
REPO_HOME = "~/dev/dotfiles"
SPEC = ".config/mise/conf.d/dotfiles.toml"
ICON = "Icon\r"

# Anchored repo-relative paths (a directory excludes everything beneath it).
REPO_ONLY = (
    ".adr-dir",
    ".gitattributes",
    ".github",
    ".gitignore",
    "LICENSE.md",
    "PLAN.md",
    "README.md",
    "build.gradle.kts",
    "crates",
    "docs",
    "gradle",
    "gradle.properties",
    "gradlew",
    "hk.pkl",
    "justfile",
    "pyproject.toml",
    "renovate.json",
    "tests",
)
LAUNCHD = ("Library/LaunchAgents", "Library/LaunchDaemons")
COPY_CLASS = (
    ".claude.json",
    ".gemini/antigravity-cli/settings.json",
    ".gemini/config/config.json",
    ".oc/config.json",
    "Library/Application Support/Claude/claude_desktop_config.json",
)
OUT_OF_REPO = {
    ".agents/skills/authoring-skills": "~/dev/agents/skills/skills/authoring-skills",
    ".agents/skills/conventional-docs": "~/dev/agents/conventional-docs/skills/conventional-docs",
    ".agents/skills/recording-changes": "~/dev/agents/skills/skills/recording-changes",
    ".agents/skills/semantic-versioning": "~/dev/agents/skills/skills/semantic-versioning",
    ".agents/skills/setup-phatblat-skills": "~/dev/agents/skills/skills/setup-phatblat-skills",
}
DANGLING = (
    ".config/iterm2/AppSupport",
    "bin/vi",
    "bin/vim",
)

_ANCHORED = REPO_ONLY + LAUNCHD + COPY_CLASS + DANGLING + tuple(OUT_OF_REPO)


def tracked(repo: Path) -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(repo), "ls-files", "-z", "--cached"],
        capture_output=True,
        check=True,
    ).stdout.decode()
    return [p for p in out.split("\0") if p]


def excluded(path: str) -> bool:
    """True when `path` is not deployed as a plain link (any other class)."""
    if ICON in path.split("/"):
        return True
    return any(path == x or path.startswith(x + "/") for x in _ANCHORED)


def link_paths(repo: Path) -> list[str]:
    return sorted(p for p in tracked(repo) if not excluded(p))


def _q(text: str) -> str:
    # JSON string escapes are a subset of TOML basic-string escapes.
    return json.dumps(text, ensure_ascii=False)


def render(repo: Path, source_root: str = REPO_HOME) -> str:
    lines = [
        "# Generated by scripts/home_spec.py from `git ls-files`; do not edit.",
        "# Regenerate with `just home-spec` (also run by `just generate`).",
        "#",
        f"# Deploys the dotfiles repo (primary checkout {source_root}) into $HOME: one",
        "# explicit `symlink` entry per file, because `symlink-each` into ~ walks the",
        "# whole home directory. Loaded as global mise config through its own deployed",
        "# link ~/.config/mise/conf.d/dotfiles.toml. Sources are absolute so `mise dot",
        "# apply` run from a linked worktree still deploys the primary checkout.",
        "#",
        "# Copyright: Ben Chatelain. MIT.",
        "",
    ]
    for path in link_paths(repo):
        lines += [
            f"[dotfiles.{_q('~/' + path)}]",
            f"source = {_q(source_root + '/' + path)}",
            'mode = "symlink"',
            "relative = false",
            "",
        ]
    for path in COPY_CLASS:
        lines += [
            f"[dotfiles.{_q('~/' + path)}]",
            f"source = {_q(source_root + '/' + path)}",
            'mode = "copy"',
            "create_if_missing = true",
            'permissions = "0600"',
            "",
        ]
    for path, source in OUT_OF_REPO.items():
        lines += [
            f"[dotfiles.{_q('~/' + path)}]",
            f"source = {_q(source)}",
            'mode = "symlink"',
            "relative = true",
            "",
        ]
    return "\n".join(lines)


def ensure_links(repo: Path) -> int:
    """Recreate the dangling-class links in $HOME with the repo's own link text."""
    home = Path(os.environ["HOME"])
    for path in DANGLING:
        text = os.readlink(repo / path)
        target = home / path
        if target.is_symlink() and os.readlink(target) == text:
            continue
        if os.path.lexists(target):
            print(f"home_spec: {target} exists and is not the expected link; left alone", file=sys.stderr)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.symlink_to(text)
        print(f"linked ~/{path} -> {text}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the mise dot deploy spec.")
    ap.add_argument("action", choices=("generate", "check", "links"))
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--source", default=REPO_HOME, help="primary checkout path written into each source")
    args = ap.parse_args()
    repo = Path(args.repo)
    if args.action == "links":
        return ensure_links(repo)
    spec = repo / SPEC
    want = render(repo, args.source)
    if args.action == "generate":
        spec.parent.mkdir(parents=True, exist_ok=True)
        if not spec.exists() or spec.read_text() != want:
            spec.write_text(want)
            print(f"wrote {SPEC}")
        return 0
    if not spec.exists() or spec.read_text() != want:
        print(f"stale: {SPEC} differs from git ls-files; run: just home-spec", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
